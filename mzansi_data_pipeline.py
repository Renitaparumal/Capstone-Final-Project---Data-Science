# mzansi_data_pipeline.py
import pandas as pd
import numpy as np
from sklearn.preprocessing import StandardScaler, MinMaxScaler
from sklearn.metrics import pairwise_distances
from sklearn.feature_selection import VarianceThreshold

class MzansiPreprocessor:
    def __init__(self, df):
        self.df = df.copy()
        self.scaler = None
        self._impute_missing_values()
        
    def _impute_missing_values(self):
        """Internal helper to handle NaNs in numeric features for scikit-learn compatibility."""
        numeric_cols = self.df.select_dtypes(include=[np.number]).columns
        for col in numeric_cols:
            if self.df[col].isnull().any():
                # Impute missing values with the median to preserve distribution shape
                self.df[col] = self.df[col].fillna(self.df[col].median())

    def handle_scale_dominance(self, features, method='standard'):
        """Applies scaling to prevent features with large ranges (e.g., income_zar) from dominating."""
        if method == 'minmax':
            self.scaler = MinMaxScaler()
        else:
            self.scaler = StandardScaler()
            
        # Fit and transform the specified features, updating the dataframe copy
        scaled_array = self.scaler.fit_transform(self.df[features])
        self.df[features] = scaled_array
        
        return self.df

    def evaluate_distance_metrics(self, features):
        """Computes Euclidean and Manhattan distances to assess geometric impact."""
        X = self.df[features].values
        
        # Compute pairwise distance matrices
        euclidean_dist = pairwise_distances(X, metric='euclidean')
        manhattan_dist = pairwise_distances(X, metric='manhattan')
        
        return {
            'euclidean': euclidean_dist,
            'manhattan': manhattan_dist
        }

    def filter_redundancy(self, features, var_threshold=0.01, corr_threshold=0.95):
        """Removes low-variance and highly correlated features to mitigate the curse of dimensionality."""
        X = self.df[features]
        
        # 1. Apply VarianceThreshold
        selector = VarianceThreshold(threshold=var_threshold)
        selector.fit(X)
        retained_mask = selector.get_support()
        surviving_features = [f for f, kept in zip(features, retained_mask) if kept]
        
        # 2. Compute correlation matrix and drop one of any pair with correlation > corr_threshold
        corr_matrix = self.df[surviving_features].corr().abs()
        upper_tri = corr_matrix.where(np.triu(np.ones(corr_matrix.shape), k=1).astype(bool))
        
        to_drop = [column for column in upper_tri.columns if any(upper_tri[column] > corr_threshold)]
        retained_features = [f for f in surviving_features if f not in to_drop]
        
        return retained_features

if __name__ == "__main__":
    # Load dataset generated by generate_mzansi_data.py
    try:
        df = pd.read_csv('mzansi_customers.csv')
    except FileNotFoundError:
        print("mzansi_customers.csv not found. Please run generate_mzansi_data.py first.")
        exit(1)
        
    # Define numeric features to process
    numeric_features = [
        'age', 'income_zar', 'stokvel_contribution_zar', 
        'mobile_money_txns', 'avg_txn_value_zar', 
        'credit_proxy_score', 'account_balance_zar', 'product_holdings'
    ]
    
    # Initialize processor
    preprocessor = MzansiPreprocessor(df)
    
    # 1. Scale Features
    scaled_df = preprocessor.handle_scale_dominance(numeric_features, method='standard')
    
    # 2. Evaluate Distance Metrics
    subset_features = ['income_zar', 'account_balance_zar', 'credit_proxy_score']
    distances = preprocessor.evaluate_distance_metrics(subset_features)
    print(f"Euclidean distance matrix shape: {distances['euclidean'].shape}")
    print(f"Manhattan distance matrix shape: {distances['manhattan'].shape}")
    
    # 3. Filter Redundancy
    retained_features = preprocessor.filter_redundancy(numeric_features)
    print(f"Retained features after filtering redundancy: {retained_features}")
    
    # 4. Data Validation Assertions
    assert scaled_df[numeric_features].isnull().sum().sum() == 0, "Validation Error: Null values remain in numeric features!"
    assert len(retained_features) > 0, "Validation Error: All features were filtered out!"
    print("Pipeline executed successfully and all assertions passed!")
